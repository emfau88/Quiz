function offlineWorker(version, paths) {
  const scope = self.registration.scope;
  const addresses = new Set(paths.map(p => new URL(p, scope).href));
  const index = new URL('index.html', scope).href;
  const entry = new URL('spielen.html', scope).href;
  const databaseName = 'quizsalon-offline-assets:' + scope;
  // Windows WebKit does not expose StorageManager and loses CacheStorage responses on cold starts.
  // Use only one asset store per installation. The separate gameplay database is never opened here.
  const useDatabase = typeof self.navigator.storage?.estimate !== 'function' && 'indexedDB' in self;
  function openDatabase() {
    return new Promise((resolve, reject) => {
      const request = self.indexedDB.open(databaseName, 1);
      request.onupgradeneeded = () => request.result.createObjectStore('files');
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => reject(request.error);
    });
  }

  async function transact(mode, work) {
    const db = await openDatabase();
    try {
      return await new Promise((resolve, reject) => {
        const tx = db.transaction('files', mode);
        const request = work(tx.objectStore('files'));
        tx.oncomplete = () => resolve(request?.result);
        tx.onabort = () => reject(tx.error || new Error('Offline asset transaction aborted'));
      });
    } finally { db.close(); }
  }

  async function download(address) {
    const response = await fetch(address, {cache:'reload', credentials:'same-origin'});
    if (!response.ok) throw new Error('Cannot install offline asset ' + address);
    const headers = new Headers(response.headers);
    // Fetch exposes decoded bytes. Wire compression and encoded lengths do not apply to a new Response.
    for (const key of ['connection', 'keep-alive', 'content-encoding', 'content-length', 'transfer-encoding']) headers.delete(key);
    return {address, body:await response.arrayBuffer(), headers:[...headers], status:response.status};
  }

  async function install() {
    if (useDatabase) {
      const records = await Promise.all([...addresses].map(download));
      await transact('readwrite', files => {
        for (const record of records) files.put(record, [version, record.address]);
      });
    } else {
      const cache = await caches.open(version);
      await cache.addAll([...addresses].map(address => new Request(address, {cache:'reload'})));
    }
    await self.skipWaiting();
  }

  async function activate() {
    if (useDatabase) {
      await transact('readwrite', files => {
        const request = files.openKeyCursor();
        request.onsuccess = () => {
          const cursor = request.result;
          if (!cursor) return;
          if (cursor.key[0] !== version) files.delete(cursor.primaryKey);
          cursor.continue();
        };
      });
    } else if (typeof self.indexedDB?.databases === 'function' &&
        (await self.indexedDB.databases()).some(db => db.name === databaseName)) {
      // An engine update can make CacheStorage available after a previous IndexedDB-backed installation.
      // Deletion also completes when a previously blocked connection closes.
      await new Promise((resolve, reject) => {
        const deletion = self.indexedDB.deleteDatabase(databaseName);
        deletion.onsuccess = deletion.onblocked = resolve;
        deletion.onerror = () => reject(deletion.error);
      });
    }
    if ('caches' in self) {
      for (const old of await caches.keys()) {
        if (old.startsWith('quizsalon-assets-') && (useDatabase || old !== version)) await caches.delete(old);
      }
    }
    await self.clients.claim();
  }

  async function read(address, request) {
    if (useDatabase) {
      const record = await transact('readonly', files => files.get([version, address]));
      if (record) return new Response(record.body, {status:record.status, headers:record.headers});
    } else {
      const response = await (await caches.open(version)).match(address);
      if (response) return response;
    }
    return fetch(request);
  }

  self.addEventListener('install', event => event.waitUntil(install()));
  self.addEventListener('activate', event => event.waitUntil(activate()));
  self.addEventListener('fetch', event => {
    const request = event.request;
    if (request.method !== 'GET') return;
    let address = request.url;
    if (request.mode === 'navigate') {
      const url = new URL(address);
      url.search = ''; url.hash = '';
      address = url.href === scope ? index : url.href;
      if (address !== index && address !== entry) return;
    }
    if (addresses.has(address)) event.respondWith(read(address, request));
  });
}
