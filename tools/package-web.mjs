const credits = await Promise.all(notices.map(async ([title,notice,url,file]) =>
  ({title,notice,url,license:file ? await readFile(file,'utf8') : ''})));
await writeFile(path.join(root,'js/credits.js'),'// Generated by tools/package-web.mjs.\nexport const CREDITS = ' + JSON.stringify(credits) + ';\n');
async function files(dir) {
  const out = [];
  for (const d of await readdir(dir,{withFileTypes:true})) {
    const file = path.join(dir,d.name);
    out.push(...(d.isDirectory() ? await files(file) : [file]));
  }
  return out.sort();
}
const assets = (await files(root)).filter(p => path.basename(p) !== 'sw.js');
const hash = createHash('sha256');
for (const p of assets) { hash.update(path.relative(root,p).split(path.sep).join('/')); hash.update(await readFile(p)); }
const version = hash.digest('hex').slice(0,16);
const urls = assets.map(p => './' + path.relative(root,p).split(path.sep).join('/'));
const sw = `// Generated by tools/package-web.mjs.
const cacheName = 'quizsalon-assets-${version}';
const paths = ${JSON.stringify(urls)};
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(cacheName);
  await cache.addAll(paths);
  await self.skipWaiting();
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const name of await caches.keys()) if (name.startsWith('quizsalon-assets-') && name !== cacheName) await caches.delete(name);
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  const scope = new URL(self.registration.scope);
  if (request.mode === 'navigate' && url.pathname !== scope.pathname && url.pathname !== scope.pathname + 'index.html') return;
  event.respondWith((async () => {
    const cache = await caches.open(cacheName);
    return (await cache.match(request.mode === 'navigate' ? new URL('./index.html',self.registration.scope) : request)) || fetch(request);
  })());
});
`;
await writeFile(path.join(root,'sw.js'),sw);
if (!options.pages && !options['sw-only']) {
  const catalog = await readFile('web/data/catalog.json','utf8');
  const bundle = await build({entryPoints:['web/js/app.js'],bundle:true,write:false,format:'iife',target:'es2021',
    plugins:[{name:'local-edition',setup(api) {
      api.onResolve({filter:/^\.\/access\.js$/},() => ({path:path.resolve('tests/local-theme-access.js')}));
      api.onResolve({filter:/^\.\/catalog\.js$/},() => ({path:'embedded',namespace:'catalog'}));
      api.onLoad({filter:/.*/,namespace:'catalog'},() => ({contents:'export async function loadCatalog(){return ' + catalog + ';}'}));
    }}]});
  const script = bundle.outputFiles[0].text.replaceAll('./assets/salon.webp',await data('web/assets/salon.webp','image/webp')).replace(/<\/script/gi,'<\\/script');
  let css = await readFile('web/styles.css','utf8');
  for (const file of ['DM-Sans.ttf','Spectral-Medium.ttf']) css = css.replace('./assets/fonts/' + file,await data('web/assets/fonts/' + file,'font/ttf'));
  let html = await readFile('web/index.html','utf8');
  html = html.replace(/\s*<link rel="manifest"[^>]+>/,'')
    .replace('./assets/icon-192.png',await data('web/assets/icon-192.png','image/png'))
    .replace('<link rel="stylesheet" href="./styles.css">',() => '<style>' + css + '</style>')
    .replace(/\s*<script type="module"[^>]*><\/script>/,'')
    .replace('</body>',() => '<script>' + script + '</script>\n</body>');
  await mkdir('release',{recursive:true});
  await writeFile(standalone,html);
  console.log(standalone + ' · ' + Buffer.byteLength(html) + ' Bytes');
}
console.log('Offline cache ' + version + ' · ' + urls.length + ' files');
